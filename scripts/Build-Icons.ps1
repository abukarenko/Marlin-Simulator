# Rebuild the small printer icons using Windows drawing primitives.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path $PSScriptRoot -Parent
foreach ($name in @('emulator','simulator')) {
    $accent = if ($name -eq 'emulator') { [Drawing.ColorTranslator]::FromHtml('#38BDF8') } else { [Drawing.ColorTranslator]::FromHtml('#FFAD46') }
    $images = @()
    foreach ($size in @(16,24,32,48,64,128,256)) {
        $bmp = [Drawing.Bitmap]::new($size,$size)
        $g = [Drawing.Graphics]::FromImage($bmp)
        $g.SmoothingMode = [Drawing.Drawing2D.SmoothingMode]::AntiAlias
        $g.ScaleTransform($size/256.0,$size/256.0)
        $bg = [Drawing.SolidBrush]::new([Drawing.ColorTranslator]::FromHtml('#172636'))
        $fg = [Drawing.SolidBrush]::new($accent)
        $white = [Drawing.SolidBrush]::new([Drawing.ColorTranslator]::FromHtml('#E8F1F8'))
        $pen = [Drawing.Pen]::new($accent,16)
        $pen.StartCap = $pen.EndCap = [Drawing.Drawing2D.LineCap]::Round
        $g.FillEllipse($bg,4,4,248,248)
        $g.DrawLine($pen,57,192,57,57); $g.DrawLine($pen,57,57,199,57); $g.DrawLine($pen,199,57,199,192)
        $g.FillRectangle($white,41,190,174,16)
        $g.FillRectangle($fg,92,74,36,29)
        $g.FillPolygon($white,[Drawing.Point[]]@([Drawing.Point]::new(100,108),[Drawing.Point]::new(120,108),[Drawing.Point]::new(110,122)))
        $g.FillRectangle($fg,109,145,49,39)
        $g.Dispose();$bg.Dispose();$fg.Dispose();$white.Dispose();$pen.Dispose()
        if ($size -eq 256) { $bmp.Save((Join-Path $root "assets/$name.png"),[Drawing.Imaging.ImageFormat]::Png) }
        $stream = [IO.MemoryStream]::new();$bmp.Save($stream,[Drawing.Imaging.ImageFormat]::Png)
        $images += ,@($size,$stream.ToArray());$stream.Dispose()
        if ($size -eq 32 -and $name -eq 'simulator') {
            $header = "// Generated by scripts/Build-Icons.ps1. RGBA pixels for SDL.`nstatic unsigned char simulator_icon_pixels[] = {`n"
            for ($y=0;$y -lt 32;$y++) {
                for ($x=0;$x -lt 32;$x++) { $c=$bmp.GetPixel($x,$y);$header += "$($c.R),$($c.G),$($c.B),$($c.A)," }
                $header += "`n"
            }
            $header += "};`n"
            [IO.File]::WriteAllText((Join-Path $root 'vendor/MarlinSimUI-29c11d4f63/src/MarlinSimulator/resources/simulator_icon.h'),$header)
        }
        $bmp.Dispose()
    }
    $output = [IO.File]::Create((Join-Path $root "assets/$name.ico"));$writer=[IO.BinaryWriter]::new($output)
    $writer.Write([uint16]0);$writer.Write([uint16]1);$writer.Write([uint16]$images.Count)
    $offset=6+16*$images.Count
    foreach ($entry in $images) {
        $dimension=if($entry[0] -eq 256){0}else{$entry[0]}
        $writer.Write([byte]$dimension);$writer.Write([byte]$dimension);$writer.Write([uint16]0)
        $writer.Write([uint16]1);$writer.Write([uint16]32);$writer.Write([uint32]$entry[1].Length);$writer.Write([uint32]$offset)
        $offset += $entry[1].Length
    }
    foreach($entry in $images){$writer.Write([byte[]]$entry[1])}
    $writer.Dispose()
}
